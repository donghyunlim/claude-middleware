import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
const home=process.env.QA_HOME; const cfg=JSON.parse(readFileSync(home+"/config.json","utf8"));
const { chromium } = createRequire(cfg.desktop_worktree+"/package.json")("playwright-core");
const b = await chromium.connectOverCDP(cfg.cdp||"http://127.0.0.1:9334");
const pages=b.contexts().flatMap(c=>c.pages()); const pg=pages.find(p=>/index|app|file/.test(p.url())||true);
const loc=pg.locator(process.argv[2]).first();
await loc.dblclick({timeout:5000});
await pg.waitForTimeout(800);
console.log((await loc.innerText()).slice(0,60));
process.exit(0);
